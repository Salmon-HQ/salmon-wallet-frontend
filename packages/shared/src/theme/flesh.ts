/** Every `x,y` pair in the authored path data. The format is uniform. */
const POINT = /(-?[\d.]+),(-?[\d.]+)/g;

/** Shifts a whole path down by `dy`, which for this data is a y-only rewrite. */
const translateY = (d: string, dy: number): string =>
  d.replace(POINT, (_, x: string, y: string) => `${x},${(Number(y) + dy).toFixed(2)}`);

/** Vertical span a path covers, so we only repeat a band where it lands. */
const yExtent = (d: string): readonly [number, number] => {
  const ys = Array.from(d.matchAll(POINT), (m) => Number(m[2]));
  return [Math.min(...ys), Math.max(...ys)];
};

/**
 * The strokes a renderer actually draws: the authored bands, repeated at the
 * tile offsets each one reaches. This is the `overflow="visible"` the DOM
 * would otherwise do for us, resolved once here so mobile gets it too.
 */
export const fleshTiledStrokes: ReadonlyArray<FleshStroke> = fleshStrokes.flatMap(
  ([d, width, strokeOpacity, fade]) => {
    const [minY, maxY] = yExtent(d);
    const half = width / 2;
    return [-fleshTile.height, 0, fleshTile.height]
      .filter((dy) => minY + dy - half < fleshTile.height && maxY + dy + half > 0)
      .map((dy): FleshStroke => [translateY(d, dy), width, strokeOpacity, fade]);
  }
);
