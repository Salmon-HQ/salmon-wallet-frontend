/**
 * Flesh geometry — the myoseptal texture of salmon flesh, as path data.
 *
 * Companion to the scales motif, and deliberately its opposite. Scales are
 * skin: the outside of the animal, and the right texture for a ground or a
 * plane. A filled button is mass, not surface — it is the inside of the
 * thing — so the honest material for it is what you see when the fish is cut
 * open: the myosepta, pale sheets of collagen and lipid separating the
 * muscle blocks.
 *
 * Anatomy this draws, and why it is shaped this way:
 *  - Each band is a W, not a V: four nested cones (dorsal/ventral,
 *    anterior/posterior) joined by two sloping parts. The mid-height part
 *    bows toward the head. (PMC9119618; van Leeuwen, JEB 202:3405)
 *  - Cone traces span more than one vertebra, so consecutive myosepta
 *    overlap in projection. The faint half-bands intruding into each gap
 *    are that overlap, and they are what stops the texture reading as
 *    parallel stripes.
 *  - Bands are PALE, never dark. The pale stripe is collagen plus the fat
 *    that concentrates in the myocommata. Dark slits mean gaping, which is
 *    a defect, not healthy flesh.
 *  - Each band fades in and out along its length rather than running edge to
 *    edge, which is the difference between flesh and wood grain.
 *
 * Two constraints shaped this data, and both are why it is baked here rather
 * than generated per platform:
 *
 *  1. NO FILTERS. `react-native-svg` (checked at 15.15.3) implements
 *     `FeTurbulence` and `FeDisplacementMap` as `warnUnimplementedFilter();
 *     return null`, so procedural noise does not exist on mobile. All the
 *     irregularity is authored into the path data below, and the soft edge is
 *     faked with stacked strokes rather than a blur. Gradients on stroke ARE
 *     natively supported, so the along-length fade is portable.
 *
 *  2. CONTRAST IS FREE. Every band is lighter than the fill it sits on, so the
 *     texture can only ever raise the luminance under a label. Worst-case
 *     contrast for ink on a salmon fill is therefore exactly the flat fill's
 *     6.50:1 — this texture cannot reduce label contrast at all. Introducing a
 *     band darker than the fill, at any opacity, would break that guarantee;
 *     `flesh.test.ts` asserts against it.
 *
 * Path data rather than an `.svg` import, for the same reason as `brand.ts`:
 * strings need no bundler support and cannot drift between platforms. Both
 * `packages/ui` and `apps/mobile` draw exactly these arrays; nothing is
 * randomised at render time.
 *
 * One portability note. The bands are authored across a range taller than the
 * tile — that overlap is the anatomy, not a mistake — which on the DOM would
 * be handled with `overflow="visible"` on the `<pattern>`. `react-native-svg`
 * has no such prop (its `Pattern` accepts x/y/width/height/viewBox/transform
 * and nothing else), so relying on it would mean mobile silently clipping a
 * third of the bands away and growing a seam at every tile edge. Instead the
 * wrap is baked: `fleshTiledStrokes` repeats each band at whatever tile
 * offsets it actually reaches, so a plainly clipped tile loses nothing and
 * both platforms draw the same thing. Renderers use that array, not the
 * authored master below.
 */

